-- Catalog as data, step 2: the platform reference catalog as rows.
-- Design: docs/catalog-as-data-design.md §2.1. Step 1 moved the catalog out of the code's
-- components into supabase/functions/_shared/catalog.mjs; this table holds the same catalog
-- as rows, seeded from it, so platform staff can add a paint line, a color or a profile
-- for every shop, or delist one, without a deploy. These are manufacturer-level facts (a
-- color's hex, a profile's takeup), public specs: anyone may read them, and the public
-- pages and the prerender will read them instead of their own copies (step 4). Only
-- platform staff write. Rows are never deleted once an order could reference them —
-- `delisted` hides a row from every picker while it still resolves for history.
--
-- submit-order reads the table from this migration on (falling back to the code default
-- when it is unreachable, empty or incomplete); the app keeps the code default until the
-- per-shop selection arrives in step 3, where the resolved catalog replaces that binding.
create table if not exists public.catalog_items (
  kind        text not null check (kind in ('brand', 'material', 'color', 'gauge', 'paint', 'profile', 'clip', 'accessory')),
  parent_key  text not null default '',   -- a color's brand, a gauge's table ('painted' or a bare metal), an accessory spec's type; '' when none
  key         text not null,              -- the name orders store: "Una-Clad", "Regal White", "24ga", 'SSQ200 – 2" Mechanical Seam'
  data        jsonb not null default '{}',-- the rest: hex, premium, label, panelSqft, trimFt, mult, code, family, takeup, vendor, desc, rules
  sort        int not null default 0,     -- list order; the color and gauge groups are ordered through it as well
  delisted    boolean not null default false,
  updated_at  timestamptz not null default now(),
  updated_by  uuid references auth.users(id) on delete set null,
  primary key (kind, parent_key, key)
);
alter table public.catalog_items enable row level security;

drop policy if exists "everyone reads the catalog" on public.catalog_items;
create policy "everyone reads the catalog" on public.catalog_items
  for select using (true);
drop policy if exists "staff insert catalog" on public.catalog_items;
create policy "staff insert catalog" on public.catalog_items
  for insert to authenticated with check (public.is_staff());
drop policy if exists "staff update catalog" on public.catalog_items;
create policy "staff update catalog" on public.catalog_items
  for update to authenticated using (public.is_staff()) with check (public.is_staff());
drop policy if exists "staff delete catalog" on public.catalog_items;
create policy "staff delete catalog" on public.catalog_items
  for delete to authenticated using (public.is_staff());

