// Writes the SQL that seeds public.catalog_items from DEFAULT_CATALOG, so the rows equal
// the code's constants exactly. Run: node scripts/catalog-seed.mjs > out.sql, and paste the
// output into a migration (the first one is 20261020155956_catalog_items.sql). Re-running it
// after the catalog changes in code gives an upsert that brings the table back in line.
import { DEFAULT_CATALOG, catalogToRows } from "../supabase/functions/_shared/catalog.mjs";

const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const rows = catalogToRows(DEFAULT_CATALOG);
const values = rows.map((r) => `  (${q(r.kind)}, ${q(r.parent_key)}, ${q(r.key)}, ${q(JSON.stringify(r.data))}::jsonb, ${r.sort}, ${r.delisted})`);
process.stdout.write(
  `-- ${rows.length} rows generated by scripts/catalog-seed.mjs from DEFAULT_CATALOG; do not edit by hand.\n` +
  `insert into public.catalog_items (kind, parent_key, key, data, sort, delisted) values\n${values.join(",\n")}\n` +
  `on conflict (kind, parent_key, key) do update set data = excluded.data, sort = excluded.sort, delisted = excluded.delisted, updated_at = now();\n`,
);
